function difference(a,b){
    return Math.abs(a-b);
}

console.log(difference(10,4));

console.log(difference(56,78));

console.log(difference(34.49823,56.782009887));


function sum(a,b,c){
    return Math.abs(a+b+c);
}

console.log(sum(3,4,7));

console.log(sum(67,23.6,56.48));

console.log(sum(7.34982,65.88342,43.89));